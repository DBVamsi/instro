from typing import Protocol


class Transport():
    def connect(self) -> None: ...

    def disconnect(self) -> None: ...

class MessageTransport(Transport):

    def read(self) -> str: ...

    def write(self, payload: str) -> None: ...

    def query(self, payload: str) -> str: ...

class ModbusTransport(Transport):
    
    def read_register(self, register: int) -> int: ...

    def write_register(self, register: int, value: int) -> None: ...

    def read_holding_registers(self, start_register: int, count: int) -> list[int]: ...

    def write_holding_registers(self, start_register: int, values: list[int]) -> None: ...
